# Builds ../hd2d-data.js for taverne-hd2d.html: the backdrop and the sheets as data URLs
# (WebGL refuses images read from file://), plus the sheet meta of meta.json.
# Run from anywhere: python3 docs/design/v2/assets/hd2d/build-data.py
import base64, json, os
H = os.path.dirname(os.path.abspath(__file__)); A = os.path.dirname(H)
meta = json.load(open(os.path.join(H, "meta.json")))
out = ["// Generated by assets/hd2d/build-data.py: images of taverne-hd2d.html as data URLs, and sheet meta.", "window.HD2D_IMG = {"]
for rel in ["maquette/a-vide.png"] + ["hd2d/%s.png" % n for n in sorted(meta)]:
    out.append('  "%s": "data:image/png;base64,%s",' % (rel, base64.b64encode(open(os.path.join(A, rel), "rb").read()).decode()))
out += ["};", "window.HD2D_META = " + json.dumps(meta) + ";"]
open(os.path.join(A, "hd2d-data.js"), "w").write("\n".join(out) + "\n")
